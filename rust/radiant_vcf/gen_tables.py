"""Generate src/tables.rs from the lookup tables of radiant/tasks/vcf/snv/germline/occurrence.py.

The Rust extraction must give the same parental origin and transmission mode as the Python one, so the tables are
generated from the Python source rather than copied by hand. Run from the repository root after any table change:

    python rust/radiant_vcf/gen_tables.py

The `tables_are_current` unit test (tests/unit/vcf/germline/test_rust_engine_parity.py) fails when the file is stale.
"""

from pathlib import Path

from radiant.tasks.vcf.snv.germline import occurrence as o

OUT = Path(__file__).parent / "src" / "tables.rs"


def calls(t: tuple) -> str:
    return "&[" + ", ".join(str(v) for v in t) + "]"


def render() -> str:
    lines = [
        "// @generated by rust/radiant_vcf/gen_tables.py from radiant/tasks/vcf/snv/germline/occurrence.py.",
        "// Do not edit by hand.",
        "",
        "pub type Calls = &'static [i32];",
        "",
    ]
    for name in ("AUTOSOMAL_ORIGINS_LOOKUP", "X_ORIGINS_LOOKUP", "Y_ORIGINS_LOOKUP"):
        table = getattr(o, name)
        lines.append(f"pub static {name}: &[(Calls, Calls, Calls, &str)] = &[")
        for (p, f, m), v in table.items():
            lines.append(f"    ({calls(p)}, {calls(f)}, {calls(m)}, {v!r}),".replace("'", '"'))
        lines.append("];")
        lines.append("")
    lines.append("pub static AUTOSOMAL_TRANSMISSION_LOOKUP: &[(Calls, Calls, Calls, bool, bool, &str)] = &[")
    for (p, f, m, fa, ma), v in o.AUTOSOMAL_TRANSMISSION_LOOKUP.items():
        lines.append(f'    ({calls(p)}, {calls(f)}, {calls(m)}, {str(fa).lower()}, {str(ma).lower()}, "{v}"),')
    lines.append("];")
    lines.append("")
    lines.append("pub static SEXUAL_TRANSMISSION_LOOKUP: &[(&str, Calls, Calls, Calls, bool, bool, &str)] = &[")
    for (g, p, f, m, fa, ma), v in o.SEXUAL_TRANSMISSION_LOOKUP.items():
        lines.append(f'    ("{g}", {calls(p)}, {calls(f)}, {calls(m)}, {str(fa).lower()}, {str(ma).lower()}, "{v}"),')
    lines.append("];")
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    OUT.write_text(render())
    print(f"wrote {OUT}")
